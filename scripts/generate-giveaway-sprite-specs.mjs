import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const spriteDirectory = path.join(repoRoot, 'public', 'giveaways', 'sprites');
const outputPath = path.join(
  repoRoot,
  'src',
  'app',
  'v',
  'giveaways',
  'generated-sprite-geometry.ts',
);

const spriteAssets = {
  closed: {
    filename: 'chest.png',
    frames: 1,
  },
  selected: {
    filename: 'chest-selected.png',
    frames: 1,
  },
  opening: {
    filename: 'chest-opening-animation.png',
    frames: 10,
  },
  winnerOpening: {
    filename: 'chest-opening-animation-winner.png',
    frames: 10,
  },
  openingMask: {
    filename: 'chest-opening-animation-mask.png',
    frames: 10,
  },
};

function formatObject(value, indentLevel = 0) {
  if (Array.isArray(value)) {
    if (value.length === 0) {
      return '[]';
    }

    const indent = '  '.repeat(indentLevel);
    const childIndent = '  '.repeat(indentLevel + 1);
    const items = value.map((item) => `${childIndent}${formatObject(item, indentLevel + 1)}`);
    return `[\n${items.join(',\n')}\n${indent}]`;
  }

  if (value && typeof value === 'object') {
    const entries = Object.entries(value);
    if (entries.length === 0) {
      return '{}';
    }

    const indent = '  '.repeat(indentLevel);
    const childIndent = '  '.repeat(indentLevel + 1);
    const props = entries.map(
      ([key, entryValue]) => `${childIndent}${key}: ${formatObject(entryValue, indentLevel + 1)}`,
    );
    return `{\n${props.join(',\n')}\n${indent}}`;
  }

  return JSON.stringify(value);
}

function getPixelAlpha(rawPixels, imageWidth, x, y) {
  const alphaIndex = ((y * imageWidth) + x) * 4 + 3;
  return rawPixels[alphaIndex];
}

function measureFrameBounds(rawPixels, imageWidth, frameWidth, frameHeight, frameIndex) {
  const startX = frameIndex * frameWidth;
  let left = frameWidth;
  let top = frameHeight;
  let right = -1;
  let bottom = -1;

  for (let y = 0; y < frameHeight; y += 1) {
    for (let x = 0; x < frameWidth; x += 1) {
      if (getPixelAlpha(rawPixels, imageWidth, startX + x, y) === 0) {
        continue;
      }

      if (x < left) {
        left = x;
      }

      if (y < top) {
        top = y;
      }

      if (x > right) {
        right = x;
      }

      if (y > bottom) {
        bottom = y;
      }
    }
  }

  if (right < 0 || bottom < 0) {
    throw new Error(`Frame ${frameIndex} has no visible pixels.`);
  }

  return { left, top, right, bottom };
}

async function readSpriteGeometry({ filename, frames }) {
  const filePath = path.join(spriteDirectory, filename);
  const { data, info } = await sharp(filePath).ensureAlpha().raw().toBuffer({ resolveWithObject: true });

  if (info.width % frames !== 0) {
    throw new Error(
      `Sprite ${filename} width ${info.width} is not evenly divisible by ${frames} frame(s).`,
    );
  }

  const frameWidth = info.width / frames;
  const frameHeight = info.height;
  const frameBounds = Array.from({ length: frames }, (_, frameIndex) =>
    measureFrameBounds(data, info.width, frameWidth, frameHeight, frameIndex),
  );

  return {
    frameWidth,
    frameHeight,
    frameBounds,
    bounds: frameBounds[0],
    finalBounds: frameBounds[frameBounds.length - 1],
  };
}

function buildGeneratedModuleContent(geometry) {
  return `// This file is auto-generated by scripts/generate-giveaway-sprite-specs.mjs.
// Run \`npm run sprites:generate\` after replacing giveaway sprite assets.

export type GeneratedSceneSpriteBounds = {
  left: number;
  top: number;
  right: number;
  bottom: number;
};

export const CHEST_SPRITE_GEOMETRY = ${formatObject(geometry, 0)} as const;
`;
}

async function writeIfChanged(filePath, content) {
  let current = null;
  try {
    current = await readFile(filePath, 'utf8');
  } catch {
    current = null;
  }

  if (current === content) {
    return false;
  }

  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, content, 'utf8');
  return true;
}

async function main() {
  const closed = await readSpriteGeometry(spriteAssets.closed);
  const selected = await readSpriteGeometry(spriteAssets.selected);
  const opening = await readSpriteGeometry(spriteAssets.opening);
  const winnerOpening = await readSpriteGeometry(spriteAssets.winnerOpening);
  const openingMask = await readSpriteGeometry(spriteAssets.openingMask);

  const geometry = {
    closed: {
      frameWidth: closed.frameWidth,
      frameHeight: closed.frameHeight,
      bounds: closed.bounds,
    },
    selected: {
      frameWidth: selected.frameWidth,
      frameHeight: selected.frameHeight,
      bounds: selected.bounds,
    },
    opening: {
      frameWidth: opening.frameWidth,
      frameHeight: opening.frameHeight,
      frameBounds: opening.frameBounds,
      finalBounds: opening.finalBounds,
    },
    winnerOpening: {
      frameWidth: winnerOpening.frameWidth,
      frameHeight: winnerOpening.frameHeight,
      frameBounds: winnerOpening.frameBounds,
      finalBounds: winnerOpening.finalBounds,
    },
    openingMask: {
      frameWidth: openingMask.frameWidth,
      frameHeight: openingMask.frameHeight,
      bounds: openingMask.bounds,
      frameBounds: openingMask.frameBounds,
      finalBounds: openingMask.finalBounds,
    },
  };

  const changed = await writeIfChanged(outputPath, buildGeneratedModuleContent(geometry));
  const status = changed ? 'updated' : 'unchanged';
  console.log(`[sprites] giveaway chest geometry ${status}: ${path.relative(repoRoot, outputPath)}`);
}

main().catch((error) => {
  console.error('[sprites] Failed to generate giveaway sprite specs.');
  console.error(error);
  process.exitCode = 1;
});
